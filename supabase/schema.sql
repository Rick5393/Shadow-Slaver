create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.profiles (id, name)
    values (new.id, coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), 'Jogador'));

    insert into public.player_characters (player_id, character_id, active)
    values (new.id, 1, true);

    insert into public.event_progress (player_id, event_code)
    values (new.id, 'lua_sangrenta');

    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.select_character(selected_character_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
    if auth.uid() is null then
        raise exception 'Autenticacao obrigatoria';
    end if;

    if not exists (
        select 1
        from public.player_characters
        where player_id = auth.uid() and character_id = selected_character_id
    ) then
        raise exception 'Personagem indisponivel';
    end if;

    update public.player_characters
    set active = (character_id = selected_character_id)
    where player_id = auth.uid();
end;
$$;

create or replace function public.complete_match(
    target_player_id uuid,
    enemies_gained integer,
    dungeons_gained integer,
    coins_gained integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    progress_row public.event_progress;
begin
    insert into public.event_progress (player_id, event_code)
    values (target_player_id, 'lua_sangrenta')
    on conflict (player_id, event_code) do nothing;

    update public.event_progress
    set enemies_killed = enemies_killed + greatest(enemies_gained, 0),
        dungeons_completed = dungeons_completed + greatest(dungeons_gained, 0)
    where player_id = target_player_id and event_code = 'lua_sangrenta'
    returning * into progress_row;

    update public.profiles
    set coins = coins + greatest(coins_gained, 0),
        last_login = now()
    where id = target_player_id;

    return to_jsonb(progress_row);
end;
$$;

revoke all on function public.complete_match(uuid, integer, integer, integer) from public;
grant execute on function public.complete_match(uuid, integer, integer, integer) to service_role;
grant execute on function public.select_character(bigint) to authenticated;

