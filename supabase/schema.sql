create extension if not exists pgcrypto;

create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    name text not null default 'Jogador',
    profile_image_url text,
    title text not null default 'Cacador das Sombras',
    account_level integer not null default 1 check (account_level > 0),
    xp integer not null default 0 check (xp >= 0),
    xp_next integer not null default 100 check (xp_next > 0),
    coins integer not null default 0 check (coins >= 0),
    rubies integer not null default 0 check (rubies >= 0),
    last_login timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.characters (
    id bigint generated by default as identity primary key,
    name text not null,
    class_name text not null,
    description text,
    image_url text,
    rarity text not null default 'comum',
    enabled boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.player_characters (
    id bigint generated by default as identity primary key,
    player_id uuid not null references auth.users(id) on delete cascade,
    character_id bigint not null references public.characters(id) on delete cascade,
    level integer not null default 1 check (level > 0),
    xp integer not null default 0 check (xp >= 0),
    xp_next integer not null default 100 check (xp_next > 0),
    active boolean not null default false,
    unlocked_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (player_id, character_id)
);

create unique index if not exists one_active_character_per_player
    on public.player_characters(player_id)
    where active;

create table if not exists public.event_progress (
    id bigint generated by default as identity primary key,
    player_id uuid not null references auth.users(id) on delete cascade,
    event_code text not null default 'lua_sangrenta',
    enemies_killed integer not null default 0 check (enemies_killed >= 0),
    dungeons_completed integer not null default 0 check (dungeons_completed >= 0),
    potions_used integer not null default 0 check (potions_used >= 0),
    bosses_defeated integer not null default 0 check (bosses_defeated >= 0),
    event_missions_completed integer not null default 0 check (event_missions_completed >= 0),
    claimed_track_reward integer not null default 0 check (claimed_track_reward >= 0),
    updated_at timestamptz not null default now(),
    unique (player_id, event_code)
);

create table if not exists public.news (
    id bigint generated by default as identity primary key,
    title text not null,
    summary text not null,
    image_url text,
    link_url text,
    enabled boolean not null default true,
    published_at timestamptz not null default now()
);

